using System.Text;

namespace ScriptAPIGenerator;

public static class CppRuntimeAPIHeaderEmitter
{
    public static string Generate(RuntimeAPIDocument document)
    {
        ArgumentNullException.ThrowIfNull(document);

        StringBuilder builder = new();

        AppendFileHeader(builder);
        AppendIncludes(builder, document);

        builder.AppendLine("namespace URay");
        builder.AppendLine("{");
        builder.AppendLine();

        AppendRuntimeAPIStruct(builder, document);
        AppendBridgeFunctions(builder, document);
        AppendFactory(builder, document);

        builder.AppendLine("} // namespace URay");

        return builder.ToString();
    }

    private static void AppendFileHeader(StringBuilder builder)
    {
        builder.AppendLine("// <auto-generated />");
        builder.AppendLine(
            "// Generated from Source/Engine/Script/Binding/RuntimeAPI.json.");
        builder.AppendLine("// Do not edit manually.");
        builder.AppendLine();
        builder.AppendLine("#pragma once");
        builder.AppendLine();
    }

    private static void AppendIncludes(
        StringBuilder builder,
        RuntimeAPIDocument document)
    {
        builder.AppendLine("#include <Core/Math/Vector3.h>");
        builder.AppendLine("#include <Core/Type/Types.h>");

        HashSet<string> modules = new(StringComparer.Ordinal);

        foreach (RuntimeAPIDefinition api in document.APIs)
        {
            if (modules.Add(api.Module))
            {
                builder.Append("#include <Engine/Script/Binding/");
                builder.Append(api.Module);
                builder.AppendLine("Bindings.h>");
            }
        }

        builder.AppendLine("#include <cstddef>");
        builder.AppendLine("#include <string_view>");

        builder.AppendLine();
    }

    private static void AppendRuntimeAPIStruct(
        StringBuilder builder,
        RuntimeAPIDocument document)
    {
        builder.AppendLine("struct RuntimeAPI");
        builder.AppendLine("{");

        foreach (RuntimeAPIDefinition api in document.APIs)
        {
            AppendFunctionPointerSignature(builder, api, "    ");
            builder.AppendLine(" = nullptr;");
            builder.AppendLine();
        }

        builder.AppendLine("};");
        builder.AppendLine();
    }

    private static void AppendBridgeFunctions(
        StringBuilder builder,
        RuntimeAPIDocument document)
    {
        builder.AppendLine("namespace RuntimeAPIBridge");
        builder.AppendLine("{");

        foreach (RuntimeAPIDefinition api in document.APIs)
        {
            AppendBridgeFunctionSignature(builder, api);
            builder.AppendLine();
            builder.AppendLine("{");

            builder.Append("    if (!userData");

            foreach (RuntimeAPIParameter parameter in api.Parameters)
            {
                if (parameter.Type == "Vector3")
                {
                    builder.Append(" || !");
                    builder.Append(GetABIParameterName(parameter));
                }
                else if (parameter.Type == "string")
                {
                    builder.Append(" || ");
                    builder.Append(parameter.Name);
                    builder.Append("Length < 0");

                    builder.Append(" || (");
                    builder.Append(parameter.Name);
                    builder.Append("Length > 0 && !");
                    builder.Append(parameter.Name);
                    builder.Append("Data)");
                }
            }

            builder.AppendLine(")");
            builder.AppendLine("        return 0;");
            builder.AppendLine();
            builder.AppendLine(
                "    auto& scriptSystem = *static_cast<ScriptSystem*>(userData);");
            builder.AppendLine();
            builder.Append("    return ");
            builder.Append(api.NativeImplementation);
            builder.AppendLine("(");
            builder.AppendLine("        scriptSystem,");

            for (int index = 0; index < api.Parameters.Count; ++index)
            {
                RuntimeAPIParameter parameter = api.Parameters[index];

                builder.Append("        ");
                builder.Append(GetHandlerArgument(parameter));

                if (index < api.Parameters.Count - 1)
                    builder.Append(',');

                builder.AppendLine();
            }

            builder.AppendLine("        )");
            builder.AppendLine("        ? 1");
            builder.AppendLine("        : 0;");
            builder.AppendLine("}");
            builder.AppendLine();
        }

        builder.AppendLine("} // namespace RuntimeAPIBridge");
        builder.AppendLine();
    }

    private static void AppendFactory(
        StringBuilder builder,
        RuntimeAPIDocument document)
    {
        builder.AppendLine("inline RuntimeAPI CreateRuntimeAPI()");
        builder.AppendLine("{");
        builder.AppendLine("    return {");

        foreach (RuntimeAPIDefinition api in document.APIs)
        {
            builder.Append("        .");
            builder.Append(api.Name);
            builder.Append(" = &RuntimeAPIBridge::");
            builder.Append(api.Name);
            builder.AppendLine(",");
        }

        builder.AppendLine("    };");
        builder.AppendLine("}");
        builder.AppendLine();
    }

    private static void AppendFunctionPointerSignature(
        StringBuilder builder,
        RuntimeAPIDefinition api,
        string indentation)
    {
        builder.Append(indentation);
        builder.Append("int32(__cdecl* ");
        builder.Append(api.Name);
        builder.AppendLine(")(");
        builder.Append(indentation);
        builder.AppendLine("    void* userData,");

        List<string> declarations = GetAllABIParameterDeclarations(api);

        for (int index = 0; index < declarations.Count; ++index)
        {
            builder.Append(indentation);
            builder.Append("    ");
            builder.Append(declarations[index]);

            if (index < declarations.Count - 1)
                builder.Append(',');

            builder.AppendLine();
        }

        builder.Append(indentation);
        builder.Append(')');
    }

    private static void AppendBridgeFunctionSignature(
        StringBuilder builder,
        RuntimeAPIDefinition api)
    {
        builder.Append("inline int32 __cdecl ");
        builder.Append(api.Name);
        builder.AppendLine("(");
        builder.AppendLine("    void* userData,");

        List<string> declarations = GetAllABIParameterDeclarations(api);

        for (int index = 0; index < declarations.Count; ++index)
        {
            builder.Append("    ");
            builder.Append(declarations[index]);

            if (index < declarations.Count - 1)
                builder.Append(',');

            builder.AppendLine();
        }

        builder.Append(')');
    }

    private static List<string> GetAllABIParameterDeclarations(RuntimeAPIDefinition api)
    {
        List<string> declarations = [];

        foreach (RuntimeAPIParameter parameter in api.Parameters)
            declarations.AddRange(GetABIParameterDeclarations(parameter));

        return declarations;
    }

    private static IReadOnlyList<string> GetABIParameterDeclarations(
        RuntimeAPIParameter parameter)
    {
        return parameter.Type switch
        {
            "u16" =>
            [
                $"uint16 {parameter.Name}"
            ],

            "u64" =>
            [
                $"uint64 {parameter.Name}"
            ],

            "Vector3" when parameter.Direction == "in" =>
            [
                $"const Vector3* {parameter.Name}",
            ],

            "Vector3" when parameter.Direction == "out" =>
            [
                $"Vector3* {GetABIParameterName(parameter)}",
            ],

            "string" when parameter.Direction == "in" =>
            [
                $"const uint8* {parameter.Name}Data",
                $"int32 {parameter.Name}Length"
            ],

            _ => throw new InvalidOperationException(
                $"Unsupported C++ parameter: " +
                $"'{parameter.Direction} {parameter.Type} {parameter.Name}'.")
        };
    }

    private static string GetABIParameterName(RuntimeAPIParameter parameter)
    {
        return parameter.Direction == "out"
            ? $"out{ToPascalCase(parameter.Name)}"
            : parameter.Name;
    }

    private static string GetHandlerArgument(RuntimeAPIParameter parameter)
    {
        return parameter.Type switch
        {
            "Vector3" =>
                $"*{GetABIParameterName(parameter)}",

            "string" =>
                $"std::string_view(" +
                $"{parameter.Name}Data " +
                $"? reinterpret_cast<const char*>({parameter.Name}Data) " +
                $": \"\", " +
                $"static_cast<std::size_t>({parameter.Name}Length))",

            _ => parameter.Name
        };
    }

    private static string ToPascalCase(string value)
    {
        if (string.IsNullOrEmpty(value))
            return value;

        return char.ToUpperInvariant(value[0]) + value[1..];
    }
}
