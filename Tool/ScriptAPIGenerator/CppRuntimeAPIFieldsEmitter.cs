using System.Text;

namespace ScriptAPIGenerator;

public static class CppRuntimeAPIFieldsEmitter
{
    public static string Generate(RuntimeAPIDocument document)
    {
        ArgumentNullException.ThrowIfNull(document);

        StringBuilder builder = new();

        builder.AppendLine("// <auto-generated />");
        builder.AppendLine("// Generated from Source/Engine/Script/Binding/RuntimeAPI.json.");
        builder.AppendLine("// Do not edit manually.");
        builder.AppendLine();

        foreach (RuntimeAPIDefinition api in document.APIs)
        {
            builder.Append("int32(__cdecl* ");
            builder.Append(api.Name);
            builder.AppendLine(")(");
            builder.AppendLine("    void* userData,");

            for (int index = 0; index < api.Parameters.Count; ++index)
            {
                RuntimeAPIParameter parameter = api.Parameters[index];

                builder.Append("    ");
                builder.Append(GetParameterDeclaration(parameter));

                if (index < api.Parameters.Count - 1)
                    builder.Append(',');

                builder.AppendLine();
            }

            builder.AppendLine(") = nullptr;");
            builder.AppendLine();
        }

        return builder.ToString();
    }

    private static string GetParameterDeclaration(RuntimeAPIParameter parameter)
    {
        return parameter.Type switch
        {
            "u64" => $"uint64 {parameter.Name}",

            "Vector3" when parameter.Direction == "in" =>
                $"const Vector3* {parameter.Name}",

            "Vector3" when parameter.Direction == "out" =>
                $"Vector3* out{ToPascalCase(parameter.Name)}",

            _ => throw new InvalidOperationException(
                $"Unsupported C++ parameter: " +
                $"'{parameter.Direction} {parameter.Type} {parameter.Name}'.")
        };
    }

    private static string ToPascalCase(string value)
    {
        if (string.IsNullOrEmpty(value))
            return value;

        return char.ToUpperInvariant(value[0]) + value[1..];
    }
}
