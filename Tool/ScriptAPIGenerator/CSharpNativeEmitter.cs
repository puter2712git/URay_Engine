using System.Text;

namespace ScriptAPIGenerator;

public static class CSharpNativeAPIEmitter
{
    public static string Generate(RuntimeAPIDocument document)
    {
        ArgumentNullException.ThrowIfNull(document);

        StringBuilder builder = new();

        builder.AppendLine("// <auto-generated />");
        builder.AppendLine("// Generated from Source/Engine/Script/Binding/RuntimeAPI.json.");
        builder.AppendLine("// Do not edit manually.");
        builder.AppendLine();
        builder.AppendLine("using System.Runtime.InteropServices;");
        builder.AppendLine();
        builder.AppendLine("namespace URay.ScriptHost;");
        builder.AppendLine();
        builder.AppendLine("[StructLayout(LayoutKind.Sequential)]");
        builder.AppendLine("public unsafe struct RuntimeAPI");
        builder.AppendLine("{");

        foreach (RuntimeAPIDefinition api in document.APIs)
        {
            builder.AppendLine("    public delegate* unmanaged[Cdecl]<");
            builder.AppendLine("        nint,");

            foreach (RuntimeAPIParameter parameter in api.Parameters)
            {
                builder.Append("        ");
                builder.Append(GetParameterType(parameter));
                builder.AppendLine(",");
            }

            builder.Append("        ");
            builder.Append(GetResultType(api.Result));
            builder.Append("> ");
            builder.Append(api.Name);
            builder.AppendLine(";");
            builder.AppendLine();
        }

        builder.AppendLine("}");

        return builder.ToString();
    }

    private static string GetResultType(string resultType)
    {
        return resultType switch
        {
            "bool" => "int",
            _ => throw new InvalidOperationException(
                $"Unsupported result type '{resultType}'.")
        };
    }

    private static string GetParameterType(RuntimeAPIParameter parameter)
    {
        return parameter.Type switch
        {
            "u64" => "ulong",
            "Vector3" => "Vector3*",
            _ => throw new InvalidOperationException(
                $"Unsupported parameter type '{parameter.Type}'.")
        };
    }
}